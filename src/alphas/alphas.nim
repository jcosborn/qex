proc `$`*(self: HisqHMC): string =
  let
    params = (
      trajectory_length: self.tau,
      number_of_trajectories: self.trajs,
      serial_RNG: self.srng.generator,
      parallel_RNG: self.prng.generator,
      beta: self.beta,
      mass: self.mass,
      hasenbusch_mass: self.hmass,
      plaquette_coefficient: Cp,
      rectangle_coefficient: Cr
    )
  result = "\n"
  if self.cmd.hasKey("ensemble"): 
    result &= "base ensemble name: " & self.cmd["ensemble"].getStr() & "\n"
  else: result &= "base ensemble name: n/a \n"
  if self.cmd.hasKey("start"): 
    result &= "starting configuration: " & $self.cmd["start"].getInt() & "\n"
  else: result &= "starting configuration: 0 \n"
  if self.cmd.hasKey("ntraj"): 
    result &= "number of trajectories: " & $self.cmd["ntraj"].getInt() & "\n"
  else: result &= "number of trajectories: 1 \n"
  result &= "\n" 
  result &= "JSON input: " & $self.jsonInfo & "\n"
  result &= "\n"
  for tag,val in params.fieldPairs: 
    result &= tag.replace("_"," ") & ": " & $(val) & "\n"
    if tag.replace("_"," ") == "serial RNG":
      let seed = self.jsonInfo["hmc"]["serial-seed"].getStr()
      result &= "serial seed: " & $seed & "\n"
    if tag.replace("_"," ") == "parallel RNG":
      let seed = self.jsonInfo["hmc"]["parallel-seed"].getStr()
      result &= "parallel seed: " & $seed & "\n"
    if tag.replace("_"," ") == "number of trajectories":
      let 
        outerInteg = self.jsonInfo["fermion"]["integrator"].getStr()
        innerInteg = self.jsonInfo["gauge"]["integrator"].getStr()
        outerSteps = $self.jsonInfo["fermion"]["steps"].getInt()
        innerSteps = $self.jsonInfo["gauge"]["steps"].getInt()
        start = self.jsonInfo["hmc"]["gauge-start"].getStr()
      result &= "outer (fermion/Hasenbusch) integrator: " & outerInteg & "\n"
      result &= "outer (fermion/Hasenbusch) steps: " & outerSteps & "\n"
      result &= "inner (gauge) integrator: " & innerInteg & "\n"
      result &= "inner (gauge) steps per outer (fermion/Hasenbusch) gauge update: " 
      result &= innerSteps & "\n"
      result &= "gauge start: " & start & "\n"
  if self.jsonInfo["action"].hasKey("unitary-projection"):
    if self.jsonInfo["action"]["unitary-projection"].hasKey("method"):
      let proj = self.jsonInfo["action"]["unitary-projection"]["method"].getStr()
      result &= "unitary projection method: " & proj & "\n"
  else: result &= "unitary projection method: newton\n"
  result &= "minimum squared residual (action CG solver): " & $self.spa.r2req & "\n"
  result &= "maximum iterations (action CG solver): " & $self.spa.maxits & "\n"
  result &= "minimum squared residual (force CG solver): " & $self.spf.r2req & "\n"
  result &= "maximum iterations (force CG solver): " & $self.spf.maxits & "\n"
  if self.jsonInfo.hasKey("measurements"):
    if self.jsonInfo["measurements"].hasKey("sources"):
      let sources = self.jsonInfo["measurements"]["sources"].getStr()
      result &= "chiral condensate sources: " & sources & "\n"
  result &= $(self.params)
  result &= "\n"
  result &= $(self.integrator)
  result &= "\n"

template newHisqHMC*(build: untyped): auto =
  ## Brief: HISQ HMC constructor template
  ## Details:
  ## Any program using this to construct the HISQ HMC object
  ## for *production running* should provide the following flags.
  ## --start: starting trajectory number
  ## --ntraj: number of trajectories
  ## --ensemble: default name for ensemble
  ## --json: location of JSON file (see "defaultInputs" for template)
  ## 
  ## Note that serial & parallel RNG are checkpointed if "read" specified 
  ## for "start" in JSON file.
  let 
    # get information
    cmd = readCMD()
    info = case cmd.hasKey("json")
      of true: readJSON(cmd["json"].getStr())
      of false: defaultInputs
    
    # create layout -- depends on user specifications
    latLayout = info["lattice-geometry"].getIntSeq()
    lo = case info.hasKey("rank-geometry")
       of true:
         case info.hasKey("simd-geometry"):
           of true:
             newLayout(
               latLayout,
               VLEN,
               info["rank-geometry"].getIntSeq(),
               info["simd-geometry"].getIntSeq()
             )
           of false: newLayout(latLayout,info["rank-geometry"].getIntSeq())
       of false: newLayout(latLayout)

    # variables injected to caller's template call
    fermionSteps {.inject.} = info["fermion"]["steps"].getInt()
    gaugeSteps {.inject.} = info["gauge"]["steps"].getInt()
    fermionIntegrator {.inject.} = info.setIntegrator("fermion")
    gaugeIntegrator {.inject.} = info.setIntegrator("gauge")
    start {.inject.} = info["hmc"]["gauge-start"].getStr()
  
  # modifiable variables inject to caller's template call
  var 
    integrator {.inject.}: Integrator
    hisq {.inject.} = HisqHMC[lo.UU,lo.FF,lo.FF0]()

  # Prepare HMC
  (
    hisq.tau,
    hisq.trajs,
    hisq.traj0,
    hisq.srng,
    hisq.prng,
    hisq.p,
    hisq.f
  ) = (
    info["hmc"]["trajectory-length"].getFloat(),
    (if cmd.hasKey("ntraj"): cmd["ntraj"].getInt() else: 1),
    (if cmd.hasKey("start"): cmd["start"].getInt() else: 0),
    newSerialRNG(info),
    lo.newParallelRNG(info),
    lo.newGauge(),
    lo.newGauge()
  )

  # Prepare HISQ
  let beta = info["action"]["beta"].getFloat()
  (
    hisq.beta,
    hisq.mass,
    hisq.hmass,
    hisq.bcs,
    hisq.params,
    hisq.spa,
    hisq.spf,
    hisq.gc
  ) = (
    beta,
    info["action"]["mass"].getFloat(),
    info["action"]["hasenbusch-mass"].getFloat(),
    "pppa",
    hisq.p.newHISQ(info),
    newSolverParams(info,"action"),
    newSolverParams(info,"force"),
    GaugeActionCoeffs(plaq: beta*Cp, rect: beta*Cr)
  )
  
  # Prepare fields
  (
    hisq.u,
    hisq.u0,
    hisq.su,
    hisq.sul,
    hisq.phi,
    hisq.hphi,
    hisq.psi,
    hisq.hpsi
  ) = (
    lo.newGauge(),
    lo.newGauge(),
    lo.newGauge(),
    lo.newGauge(),
    lo.ColorVector(),
    lo.ColorVector(),
    lo.ColorVector(),
    lo.ColorVector()
  )
  case start:
    of "cold","frozen","symmetric": hisq.u.unit()
    of "hot","random": 
      hisq.prng.random(hisq.u) 
      hisq.u.reunit()
    else: discard
  hisq.stag = newStag3(hisq.su, hisq.sul)

  # Execute user commands and return result
  template u: untyped {.inject.} = hisq.u
  build
  hisq.integrator = integrator
  hisq.jsonInfo = info
  hisq.cmd = cmd
  hisq

