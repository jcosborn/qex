  proc polyakov[T](u: T) =
    let pg = u[0].l.physGeom
    var pl = newseq[typeof(u.wline @[1])](pg.len)
    for i in 0..<pg.len:
      pl[i] = u.wline repeat(i+1, pg[i])
    let
      pls = pl[0..^2].sum / float(pl.len-1)
      plt = pl[^1]
    echo "MEASploop spatial: ",pls.re," ",pls.im," temporal: ",plt.re," ",plt.im

