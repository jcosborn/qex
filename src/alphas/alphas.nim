proc fermionForce[S,T](
    f: auto; 
    smearedForce: proc; 
    p,hp: S; 
    g: T; 
    ffac,hfac: float
  ) =
  # reverse accumulation of the derivative
  var
    f1 = f.newOneOf()
    f3 = f.newOneOf()
    ff = f.newOneOf()
    t,t3: array[4,Shifter[typeof(p),typeof(p[0])]]
    ht,ht3: array[4,Shifter[typeof(hp),typeof(hp[0])]]

  # Prepare shifts
  for mu in 0..<f.len:
    # Single shift
    t[mu] = newShifter(p,mu,1)
    ht[mu] = newShifter(hp,mu,1)
    discard t[mu] ^* p
    discard ht[mu] ^* hp

    # Triple shift
    t3[mu] = newShifter(p,mu,3)
    ht3[mu] = newShifter(hp,mu,3)
    discard t3[mu] ^* p
    discard ht3[mu] ^* hp

  # 1. Dslash
  const n = p[0].len
  threads:
    for mu in 0..<f.len:
      for i in f[mu]: # Heavy fermion
        forO a, 0, n-1:
          forO b, 0, n-1:
            f1[mu][i][a,b] := ffac * p[i][a] * t[mu].field[i][b].adj
            f3[mu][i][a,b] := ffac * p[i][a] * t3[mu].field[i][b].adj
    threadBarrier()  
    for mu in 0..<f.len:
      for i in f[mu]: # Hasenbusch fermion
        forO a, 0, n-1:
          forO b, 0, n-1:
            f1[mu][i][a,b] += hfac * hp[i][a] * ht[mu].field[i][b].adj
            f3[mu][i][a,b] += hfac * hp[i][a] * ht3[mu].field[i][b].adj

  # 2. correcting phase
  threads:
    g.rephase
    for mu in 0..<f.len:
      for i in f[mu].odd:
        f1[mu][i] *= -1
        f3[mu][i] *= -1

  # 3. smearing
  ff.smearedForce(f1,f3)

  # 4. Tₐ ReTr( Tₐ U F† )
  threads:
    for mu in 0..<f.len:
      for i in f[mu]: f1[mu][i] := ff[mu][i] * g[mu][i].adj
    threadBarrier()
    g.rephase
    for mu in 0..<f.len:
      for i in f[mu]: f[mu][i].projectTAH(f1[mu][i])

proc sq(x: float): float = x*x

proc forceSolve[T](
    stag: auto; 
    psi: auto; 
    phi: T; 
    mass: float; 
    sp0: var SolverParams
  ) =
  tic()
  var
    varphi = newOneOf(psi)
    r = newOneOf(phi)
    r2,b2: float
    sp = sp0

  # Prepare solver parameters
  sp.resetStats()
  dec sp.verbosity
  sp.usePrevSoln = false
  threads:
    psi := 0
    let b2t = phi.norm2
    threadBarrier()
    threadMaster: b2 = b2t

  # Get solution
  stag.solveEE(varphi,phi,mass,sp)
  threads:
    # Get residual
    var r2t: float
    stag.D(r,varphi,mass)
    threadBarrier()
    r2t = r.norm2
    threadBarrier()
    threadMaster: r2 = r2t

    # Get solution for force
    varphi.even := 4.0*varphi
    threadBarrier()
    stagD2(stag.so,psi,stag.g,varphi,0,0)
    threadBarrier()
    psi.even := varphi

  # Get information about solve
  sp.r2.init r2/b2
  sp.calls = 1
  sp.seconds = getElapsedTime()
  sp.flops += float((stag.g.len*4*72+24)*psi.l.nEven) # ???
  if sp0.verbosity>0: echo "stagSolve: ", sp.getStats
  sp0.addStats(sp)

proc fermionForce*(self: var HisqHMC; dtau: float) =
  let 
    smearedForce = self.params.smearRephase(self.u,self.su,self.sul)
    ffac = 0.25*dtau
    hfac = ffac*(self.hmass.sq-self.mass.sq)
  self.stag.forceSolve(self.psi,self.phi,self.hmass,self.spf)
  self.stag.forceSolve(self.hpsi,self.hphi,self.mass,self.spf)
  self.f.fermionForce(smearedForce,self.psi,self.hpsi,self.u,ffac,hfac)

proc gaugeForce*(self: var HisqHMC) = self.gc.gaugeForce(self.u,self.f)

proc updateGauge[T](u: auto; p: T; dtau: float) =
  threads:
    for mu in 0..<u.len:
      for s in u[mu]: u[mu][s] := exp(dtau*p[mu][s])*u[mu][s]

proc updateGauge*(self: var HisqHMC; dtau: float) =
  self.u.updateGauge(self.p,dtau)
  GC_fullCollect()

proc updateMomentum[T](p: auto; f: T; dtau: float) =
  threads:
    for mu in 0..<f.len: p[mu] -= dtau*f[mu]
  GC_fullCollect()

proc updateMomentum[T](p: auto; f: T) =
  threads:
    for mu in 0..<f.len: p[mu] -= f[mu]
  GC_fullCollect()

proc updateMomentum*(self: var HisqHMC; dtau: float) =
  self.p.updateMomentum(self.f,dtau)

proc updateMomentum*(self: var HisqHMC) = self.p.updateMomentum(self.f)

proc updateMomentumFermion*(self: var HisqHMC; dtau: float) =
  self.fermionForce(dtau)
  self.updateMomentum()

proc updateMomentumGauge*(self: var HisqHMC; dtau: float) =
  self.gaugeForce()
  self.updateMomentum(dtau)

#[ Hamiltonian Monte Carlo methods ]#

template finish*(self: var HisqHMC; input: untyped) =
  # Smear & calculate final Hamiltonian
  self.smear()
  self.hf = self.hamiltonian()
  
  # Get information accessible to user
  var 
    info {.inject.} = (dH:0.0,expdH:0.0,rnd:0.0)
    metropolis = true
    accepted {.inject.}: bool
  info.dH = self.hf - self.hi
  info.expdH = exp(-info.dH)
  if self.jsonInfo["hmc"].hasKey("metropolis"):
    metropolis = self.jsonInfo["hmc"]["metropolis"].getBool()
  if metropolis:
    info.rnd = self.srng.uniform
    accepted = info.rnd <= info.expdH
  else:
    info.rnd = 0
    accepted = true
  template u: untyped {.inject.} = self.u

  # Do metropolis & have user do what they will
  case accepted:
    of true: reunit(self.u)
    of false: self.revert()
  input

proc finish*(self: var HisqHMC): bool {.discardable.} =
  self.finish: result = accepted

template sample*(self: var HisqHMC; work: untyped) =
  for traj in hmc.traj0..<hmc.trajs+hmc.traj0: 
    let trajectory {.inject.} = traj
    work

proc fermionForceCheck*(self: var HisqHMC; eps: float): float =
  proc contract[T](p,f: T): float =
    var dS: float
    threads:
      var dSt = 0.0
      for mu in 0..<p.len: dSt = dSt - reTrMul(p[mu],f[mu])
      threadMaster: dS = dSt
    result = dS
  result = eps*contract(self.p,self.f)

#[ Gradient flow ]#

template gradientFlow(
    gc: GaugeActionCoeffs; 
    g: array|seq; 
    steps: int;
    eps: float; 
    measure: untyped
  ): untyped =
  #[ Gradient flow w/ Wilson or rectangle action
     Originally written by James Osborn & Xiaoyong Jin.
     d/dt Vt = Z(Vt) Vt
     Runge-Kutta:
     W0 <- Vt
     W1 <- exp(1/4 Z0) W0
     W2 <- exp(8/9 Z1 - 17/36 Z0) W1
     V(t+eps) <- exp(3/4 Z2 - 8/9 Z1 + 17/36 Z0) W2
     where
     Zi = eps Z(Wi)
  ]#
  proc flowProc {.gensym.} =
    tic("flowProc")
    const nc = g[0][0].nrows.float
    var
      p = g[0].l.newGauge  # mom
      f = g[0].l.newGauge  # force
      n = 1
    while true:
      let t = n * eps
      let epsnc = eps * nc  # compensate force normalization
      gc.gaugeForce(g,f)
      threads:
        for mu in 0..<f.len:
          for e in g[mu]:
            var v {.noinit.}:type(load1(f[0][0]))
            v := (-1.0/4.0)*epsnc*f[mu][e]
            let t = exp(v)*g[mu][e]
            p[mu][e] := v
            g[mu][e] := t
      gc.gaugeForce(g,f)
      threads:
        for mu in 0..<f.len:
          for e in g[mu]:
            var v {.noinit.}:type(load1(f[0][0]))
            v := (-8.0/9.0)*epsnc*f[mu][e] + (-17.0/9.0)*p[mu][e]
            let t = exp(v)*g[mu][e]
            p[mu][e] := v
            g[mu][e] := t
      gc.gaugeForce(g,f)
      threads:
        for mu in 0..<f.len:
          for e in g[mu]:
            var v {.noinit.}:type(load1(f[0][0]))
            v := (-3.0/4.0)*epsnc*f[mu][e] - p[mu][e]
            let t = exp(v)*g[mu][e]
            g[mu][e] := t
      let wflowT {.inject.} = t
      measure
      inc n
      if steps>0 and n>steps: break
    toc("end")
  flowProc()

template gradientFlow(
    gc: GaugeActionCoeffs;
    g: array|seq; 
    eps: float; 
    measure: untyped
  ): untyped = 
  gc.gradientFlow(g,0,eps):
    let flowTime {.inject.} = wflowT
    measure

proc flowMeasurements(u: auto; loop: int; tau: float): JsonNode =
  var
    pls,plt: ComplexProxy[ComplexObj[float64,float64]]
    poly: seq[ComplexProxy[ComplexObj[float64,float64]]]
    t2Ess,t2Est,t2Ees,t2Eet: float
  let
    f = u.fmunu(loop)
    (es, et) = f.densityE
    q = f.topoQ
    pl = u.plaq
    nl = pl.len div 2
    ss = 6.0*pl[0..<nl].sum
    st = 6.0*pl[nl..^1].sum
    pg = u[0].l.physGeom
  poly = newSeq[ComplexProxy[ComplexObj[float64,float64]]](pg.len)
  for i in 0..<pg.len: poly[i] = u.wline repeat(i+1,pg[i])
  pls = poly[0..^2].sum/float(poly.len-1)
  plt = poly[^1]
  (t2Ess,t2Est) = (6.0*tau*tau*(3.0-ss),6.0*tau*tau*(3.0-st))
  (t2Ees,t2Eet) = (tau*tau*es,tau*tau*et)
  result = %* {
    "flow-time": tau,
    "plaquette":0.5*ss+0.5*st,
    "clover":es+et,
    "t2E-plaquette":t2Ess+t2Est,
    "t2E-clover":t2Ees+t2Eet,
    "t2E-spacelike-plaquette":t2Ess,
    "t2E-timelike-plaquette":t2Est,
    "t2E-spacelike-clover":t2Ees,
    "t2E-timelike-clover":t2Eet,
    "topological-charge":q,
    "Re(spacelike-Polyakov-loop)":3.0*pls.re,
    "Im(spacelike-Polyakov-loop)":3.0*pls.im,
    "Re(timelike-Polyakov-loop)":3.0*plt.re,
    "Im(timelike-Polyakov-loop)":3.0*plt.im,
  }

proc get(info:JsonNode;key:string): seq[float] = 
  result = newSeq[float]()
  for el in info[key].getElems(): result.add getFloat(el)

template gradientFlow*(u: auto; info: JsonNode; body: untyped) =
  var 
    v = u[0].l.newGauge
    f {.inject,used.}: File
    tau {.inject.}: float
    measurements {.inject.}: JsonNode
  for flow,flowInfo in info:
    let
      loops = case info[flow].hasKey("loops")
        of true: info[flow]["loops"].getInt()
        of false: 1
      beta = case info[flow].hasKey("beta")
        of true: info[flow]["beta"].getFloat()
        of false: 1.0
      cr = case info[flow]["action"].getStr()
        of "Rectangle": info[flow]["cr"].getFloat()
        else: 0.0
      gc = case info[flow]["action"].getStr()
        of "Rectangle": gaugeActRect(beta,cr)
        else: GaugeActionCoeffs(plaq:beta)
      fn = info[flow]["path"].getStr() & info[flow]["filename"].getStr()
      dts = info[flow].get("time-increments")
      maxFlts = info[flow].get("maximum-flow-times")
    var lastMaxFlt = 0.0
    threads: v := u
    v.reunit
    f = fn.open(fmWrite)
    for flowTimeInfo in zip(dts,maxFlts):
      let (dtau,tmax) = flowTimeInfo
      gc.gradientFlow(v,dtau):
        tau = flowTime + lastMaxFlt
        if tau > tmax: break
        measurements = v.flowMeasurements(loops,tau)
        body
      lastMaxFlt = tmax
    f.close()
      
proc formatMeasurements*(
    measurements: JsonNode;
    style: string = "default"
  ): string =
  result = ""
  let tau = measurements["flow-time"].getFloat()
  case style:
    of "default":
      var concatenation = @["FLOW",tau.formatFloat(ffDecimal,3)]
      result = concatenation.join(" ")
      for key,measurement in measurements:
        let O = measurement.getFloat()
        concatenation = @[result,O.formatFloat(ffDecimal,13)] 
        result = concatenation.join(" ")
    of "KS_nHYP_FA": # Style of https://github.com/daschaich/KS_nHYP_FA
      let
        standIn = %* {"stand-in": 0.0}
        observables = @[
          measurements["plaquette"],
          measurements["clover"],
          measurements["t2E-clover"],
          standIn["stand-in"], # i.e., nothing; where rectangle could be
          measurements["t2E-plaquette"],
          measurements["topological-charge"],
          measurements["t2E-spacelike-clover"],
          measurements["t2E-timelike-clover"],
          measurements["Re(timelike-Polyakov-loop)"],
          measurements["Im(timelike-Polyakov-loop)"],
          measurements["Re(spacelike-Polyakov-loop)"],
          measurements["Im(spacelike-Polyakov-loop)"]
        ]
      var concatenation = @["FLOW",tau.formatFloat(ffDecimal,2)]
      result = concatenation.join(" ")
      for observable in observables:
        let O = observable.getFloat()
        concatenation = @[result,O.formatFloat(ffDecimal,13)] 
        result = concatenation.join(" ")
    else: discard

