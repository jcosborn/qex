  return self.params.smearRephase(self.u,self.su,self.sul)

#[ Hamiltonian calculation methods ]#

proc pnorm2[T](p: T): float =
  var p2: float
  threads:
    var p2t = 0.0
    for mu in 0..<p.len: p2t += p[mu].pnorm2
    threadBarrier()
    threadMaster: p2 = p2t
  return p2

proc zeroFermion(phi: auto) =
  threads: phi := 0

proc kineticAction*(self: HisqHMC): float = 0.5*self.p.pnorm2

proc gaugeAction*(self: HisqHMC): float = self.gc.gaugeActionOneLoopHISQ(self.u)

proc fermionAction*(self: HisqHMC): float =
  var 
    hpsit = self.u[0].l.ColorVector()
    fact: float
  self.psi.zeroFermion()
  self.hpsi.zeroFermion()
  threads: self.stag.D(hpsit,self.hphi,-self.hmass)
  self.stag.solve(self.psi,self.phi,-self.hmass,self.spa)
  self.stag.solve(self.hpsi,hpsit,-self.mass,self.spa)
  threads:
    let factt = self.psi.norm2() + self.hpsi.norm2()
    threadBarrier()
    threadMaster: fact = factt
  return 0.5*fact 

proc hamiltonian(self: HisqHMC): float =
  var h = (kinetic: 0.0, gauge: 0.0, fermion: 0.0)
  h.kinetic = self.kineticAction()
  h.gauge = self.gaugeAction()
  h.fermion = self.fermionAction()
  var prnt = ""
  for tag,val in h.fieldPairs: prnt = prnt & tag & ": " & $(val) & " "
  echo prnt
  result = h.kinetic + h.gauge + h.fermion

#[ Heatbath methods ]#

proc pseudofermion(
    stag: auto; 
    phi,hphi: auto;
    psi,hpsi: auto; 
    mass,hmass: float;
    spa: var SolverParams
  ) =
  var hphit = psi.l.ColorVector()
  threads:
    stag.D(phi,psi,-hmass)
    stag.D(hphit,hpsi,-mass)
  stag.solve(hphi,hphit,-hmass,spa)
  threads:
    phi.odd := 0
    hphi.odd := 0

proc momentumHeatbath*(self: var HisqHMC) = self.prng.randomTAHGaussian(self.p)

proc fermionHeatbath*(self: var HisqHMC) =
  self.prng.randomComplexGaussian(self.hpsi)
  self.prng.randomComplexGaussian(self.psi)
  self.stag.pseudofermion(
    self.phi, self.hphi,
    self.psi, self.hpsi,
    self.mass, self.hmass,
    self.spa
  )

proc prepare*(self: var HisqHMC) =
  self.backup()
  self.smear()
  self.momentumHeatbath()
  self.fermionHeatbath()
  self.hi = self.hamiltonian()

