## Details:
## This is a copy of examples/hisqhmc_h.nim with added utilities for alphas
## 
## HISQ HMC with Hasenbusch preconditioning. Note that this specific code
## does not come with support for rooting. Additionally, the tadpole 
## factor is set to unity, so that the gauge action is plaquette + rectangle. 
## Due to the way in which the plaquette and rectangle coefficients are set,
## the bare gauge coupling automatically inherits the MILC convention of
## beta = 10/g_0^2, as opposed to the conventional beta = 6/g_0^2. 
## 
## This code can be used both as a standalone program and as a module that
## is to be imported by a standalone program. See the code under "isMainModule"
## for an example of how to deploy it for your purposes. 
## 
## Information is specified to program by input flags and a JSON file. See
## "newHISQHMC" input flags and "defaultInputs" for an example of what goes 
## into the JSON file.

