proc foldC(c: openArray[float]): seq[float] =
  ## Periodic fold to dt = 0..nt/2 (average of dt and nt-dt).
  result = newSeq[float](nt2 + 1)
  for dt in 0..nt2:
    result[dt] = 0.5*(c[dt] + c[(nt - dt) mod nt])

