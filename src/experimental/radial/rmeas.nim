proc currentOps(): seq[tuple[l, m: int]] =
  result = @[(0, 0)]
  for lh in 1..lmaxJ:
    for mh in -lh..lh: result.add (lh, mh)

func opIndex(lh, mh: int): int =
  ## Position of (l, m) in `currentOps`: (0,0) first, then l = 1.. with m ascending.
  lh*lh + mh + lh

proc measCurrents(u: Gauge, traj: int) =
  ## Factorized noise estimator (doc/07 1.1-1.3, WP-I production path):
  ## per (l, m) the folded, t1-averaged same-op product
  ##   k(dt) = <a(t1+dt) b(t1)>,  E[k] = tr[K_lm(t2) S K_lm(t1) S],
  ## so the physical connected correlator per 4-component flavor is -2 Re k.
  ## With -disc: the unbiased cross-sample product P(dt) estimating
  ## T(t2) T(t1) with T = 2 Re tr[K S] (this configuration's value), plus the
  ## per-slice trace itself -- the vector channel is assembled at analysis
  ## time as C_V = -2 Re k + Nf (P - <T>^2).
  var wardKeys: seq[(string, string)]
  if ward:
    actOp.r2inner = r2ptIn
    actOp.r2outer = r2ptOut
    let
      ta = wardTimes[0]
      tb = wardTimes[1]
      (c, jump) = wardChargeScan(actOp, u, mass, v5, ta, tb)
    var
      mIn = complex64(0.0, 0.0)
      mOut = complex64(0.0, 0.0)
    for t in 0..<nt:
      if t >= ta and t < tb: mIn += c[t]
      else: mOut += c[t]
    mIn = mIn/float(tb - ta)
    mOut = mOut/float(nt - (tb - ta))
    var dev = 0.0
    for t in 0..<nt:
      let d = if t >= ta and t < tb: abs(c[t] - mIn) else: abs(c[t] - mOut)
      dev = max(dev, d)
    let
      ja = abs(jump)
      wardFlat = dev/ja
      wardJump = abs(mOut - mIn - jump)/ja
    wardKeys = @[("ward_flat", &"{wardFlat:.17g}"), ("ward_jump", &"{wardJump:.17g}")]
    echo &"  ward traj {traj}: plateau flatness {wardFlat:.3e}" &
         &"  jump deviation {wardJump:.3e}  (rel to |i S_ba| = {ja:.3e})"

  actOp.r2inner = r2nzIn
  actOp.r2outer = r2nzOut
  let ops = currentOps()
  let nop = ops.len
  var w = newSeq[seq[float]](nop)
  for k in 0..<nop:
    w[k] = newSeq[float](sph.nv)
    for y in 0..<sph.nv: w[k][y] = ylm(ops[k].l, ops[k].m, sph.pos[y])
  var r = keyedRng(uint64(seed), traj, pkCurr)
  var samples = newSeq[CurrentSample](npair)
  for k in 0..<npair:
    samples[k] = currentSample(actOp, u, mass, w, r)
  # same-op connected products, folded and t1-averaged (meas/observables.connFold)
  var cl, cm, cdt, kre, kim, kerr: seq[float]
  for iop in 0..<nop:
    let (m, e) = sampleMean(connFold(samples, nt, iop, iop))
    for dt in 0..nt2:
      cl.add float(ops[iop].l)
      cm.add float(ops[iop].m)
      cdt.add float(dt)
      kre.add m[dt].re
      kim.add m[dt].im
      kerr.add e[dt]
  writeTsv(opath("currents", traj),
           measMeta("currents", traj,
             ("estimator", "factorized noise, tr[K S K S]; C_conn = -2 Re k")) & wardKeys,
           ["l", "m", "dt", "kre", "kim", "kerr"],
           [cl, cm, cdt, kre, kim, kerr])
  # cross-m connected products per l: the (2l+1) x (2l+1) correlator matrices
  var ml, mm1, mm2, mdt, mc: seq[float]
  for lh in 1..lmaxJ:
    for i1 in -lh..lh:
      for i2 in -lh..lh:
        let (m, _) = sampleMean(connFold(samples, nt, opIndex(lh, i1), opIndex(lh, i2)))
        for dt in 0..nt2:
          ml.add float(lh)
          mm1.add float(i1)
          mm2.add float(i2)
          mdt.add float(dt)
          mc.add m[dt].re
  writeTsv(opath("currmat", traj),
           measMeta("currents", traj,
             ("estimator", "cross-m folded connected products, Re tr[K_m1 S K_m2 S]")),
           ["l", "m1", "m2", "dt", "c"], [ml, mm1, mm2, mdt, mc])
  if disc:
    # one-point traces T = 2 Re tr[K S] (vector) and tau = 2 Im tr[K S] (block
    # axial) and their unbiased cross-sample products (meas/observables)
    var
      dl, dm, ddt, dp, dpi: seq[float]
      tl, tm, tt, tre, tim: seq[float]
    for iop in 0..<nop:
      let
        xr = traceSeries(samples, nt, iop)
        xi = traceSeries(samples, nt, iop, im = true)
        pr = crossFold(xr, nt)
        pim = crossFold(xi, nt)
        mr = seriesMean(xr)
        mi = seriesMean(xi)
      for dt in 0..nt2:
        dl.add float(ops[iop].l)
        dm.add float(ops[iop].m)
        ddt.add float(dt)
        dp.add pr[dt]
        dpi.add pim[dt]
      for t in 0..<nt:
        tl.add float(ops[iop].l)
        tm.add float(ops[iop].m)
        tt.add float(t)
        tre.add mr[t]
        tim.add mi[t]
    writeTsv(opath("currdisc", traj),
             measMeta("currents", traj,
               ("estimator", "cross-sample <T(t2)T(t1)> (p) and <tau(t2)tau(t1)> (pim)")),
             ["l", "m", "dt", "p", "pim"], [dl, dm, ddt, dp, dpi])
    writeTsv(opath("currtrace", traj), measMeta("currents", traj),
             ["l", "m", "t", "tre", "tim"], [tl, tm, tt, tre, tim])
  echo &"  currents traj {traj}: {nop} ops x {npair} pairs" &
       (if disc: " + one-point traces" else: "")

proc measScalars(u: Gauge, traj: int) =
  ## Point-source connected correlators from the 5-fold vertex (precise, the
  ## deck-style connected effective masses), then the volume-averaged stochastic
  ## estimators: the connected trace k(dt) = Re tr[P_t2 S P_t1 S], the one-point
  ## functions <sigma_PS(t)>, <sigma_FS(t)> and their cross-sample products --
  ## the ingredients of the full (hairpin-included) correlators assembled at
  ## analysis time (doc/07 section 3).
  actOp.r2inner = r2ptIn
  actOp.r2outer = r2ptOut
  var
    ps = newSeq[float](nt)
    fs = newSeq[float](nt)
  for t0 in srcTimes:
    let (p, f) = scalarCorrPoint(actOp, u, mass, v5, t0)
    for dt in 0..<nt:
      ps[dt] += p[dt]/float(nscalarSrc)
      fs[dt] += f[dt]/float(nscalarSrc)
  var dev = 0.0
  var scale = 0.0
  for dt in 0..<nt:
    scale = max(scale, abs(ps[dt]))
    if dt != 0: dev = max(dev, abs(ps[dt] - fs[dt]))
  let psfs = dev/scale
  # At dt != 0 this contraction makes PS == FS bitwise at m = 0 (z2 = conj(z1),
  # a GW identity, not a measurement); the statement with content is dt = 0,
  # where FS keeps its contact term and (S + S^dag)_{xx} = 2 makes it cancel.
  let contact = abs(ps[0] - fs[0])/scale
  var cdt = newSeq[float](nt)
  for dt in 0..<nt: cdt[dt] = float(dt)
  writeTsv(opath("scalars", traj),
           measMeta("scalars", traj, ("psfs_maxdev", &"{psfs:.17g}"),
                    ("psfs_contact", &"{contact:.17g}")),
           ["dt", "ps", "fs"], [cdt, ps, fs])
  # volume-averaged stochastic estimators
  actOp.r2inner = r2nzIn
  actOp.r2outer = r2nzOut
  var r = keyedRng(uint64(seed), traj, pkScal)
  var samples = newSeq[CurrentSample](nscalarPair)
  for k in 0..<nscalarPair: samples[k] = scalarSample(actOp, u, mass, r)
  let
    (km, ke) = sampleMean(connFold(samples, nt, 0, 0))
    xr = traceSeries(samples, nt, 0)
    xi = traceSeries(samples, nt, 0, im = true)
  # per-sample one-point functions O_FS = a + i b, O_PS = c from T_k(t) = d_k(t)
  var fa, fb, fc: seq[seq[float]]
  for k in 0..<nscalarPair:
    var a, b, c: seq[float]
    for t in 0..<nt:
      let op = scalarOnePoint(complex64(0.5*xr[k][t], 0.5*xi[k][t]), sph.nv, mass)
      a.add op.fs.re
      b.add op.fs.im
      c.add op.ps
    fa.add a
    fb.add b
    fc.add c
  let
    paa = crossFold(fa, nt)
    pbb = crossFold(fb, nt)
    pcc = crossFold(fc, nt)
    mfa = seriesMean(fa)
    mfb = seriesMean(fb)
    mfc = seriesMean(fc)
    mtr = seriesMean(xr)
  var vdt, vk, vke, vaa, vbb, vcc: seq[float]
  for dt in 0..nt2:
    vdt.add float(dt)
    vk.add km[dt].re
    vke.add ke[dt]
    vaa.add paa[dt]
    vbb.add pbb[dt]
    vcc.add pcc[dt]
  writeTsv(opath("scalarvol", traj),
           measMeta("scalars", traj,
             ("k", "folded Re tr[P_t2 S P_t1 S], volume-averaged connected trace"),
             ("p", "cross-sample <O(t2) O(t1)>: aa/bb = Re/Im sigma_FS, cc = sigma_PS")),
           ["dt", "kre", "kerr", "paa", "pbb", "pcc"], [vdt, vk, vke, vaa, vbb, vcc])
  var st, sfa, sfb, sfc, strr: seq[float]
  for t in 0..<nt:
    st.add float(t)
    sfa.add mfa[t]
    sfb.add mfb[t]
    sfc.add mfc[t]
    strr.add 0.5*mtr[t]
  writeTsv(opath("scalardisc", traj),
           measMeta("scalars", traj,
             ("onepoint", "<sigma_FS(t)> = fsre + i fsim, <sigma_PS(t)> = ps, Re tr[P_t S] = trre")),
           ["t", "fsre", "fsim", "ps", "trre"], [st, sfa, sfb, sfc, strr])
  echo &"  scalars traj {traj}: PS==FS dt!=0 dev {psfs:.3e}" &
       &"  dt=0 GW contact dev {contact:.3e}" &
       (if mass != 0.0: "  (m != 0: equality not expected)" else: "") &
       &"  + {nscalarPair} volume pairs"

proc measGluon(u: Gauge, traj: int) =
  ## Flow a copy; at each flow time (0 first) measure E_s/E_t, the folded
  ## m-averaged loop correlator matrices for l = 1, 2, and the folded F^2
  ## l = 0 correlator (RAW: vacuum subtraction happens at analysis time).
  let nsh = shapes.len
  var
    fS, fEs, fEt: seq[float]                       # flow.t
    gS, gL, gI, gJ, gDt, gC: seq[float]            # loops.t
    f2S, f2Dt, f2C: seq[float]                     # f2.t
  var uf = newGauge(lat)
  uf := u
  flowRun(lat, uf, btFlow, stimes, flowStep, RK4CK_2N,
    proc(s: float, v: Gauge) =
      fS.add s
      fEs.add energyDensity(lat, v, bt)
      fEt.add energyDensityT(lat, v, bt)
      for lh in 1..2:
        let nm = 2*lh + 1
        var o = newSeq[seq[seq[float]]](nsh)
        for ish in 0..<nsh:
          o[ish] = newSeq[seq[float]](nm)
          for im in 0..<nm:
            o[ish][im] = loopProject(lat, v, shapes[ish], lh, im - lh)
        for i in 0..<nsh:
          for j in 0..<nsh:
            var raw = newSeq[float](nt)
            for dt in 0..<nt:
              var acc = 0.0
              for im in 0..<nm:
                for t1 in 0..<nt:
                  acc += o[i][im][(t1 + dt) mod nt]*o[j][im][t1]
              raw[dt] = acc/float(nm*nt)
            # raw_ij(nt-dt) = raw_ji(dt) by the t1 average, so this fold both
            # folds about nt/2 and symmetrizes the matrix
            for dt in 0..nt2:
              gS.add s
              gL.add float(lh)
              gI.add float(i)
              gJ.add float(j)
              gDt.add float(dt)
              gC.add 0.5*(raw[dt] + raw[(nt - dt) mod nt])
      let of2 = f2Project(lat, v, 0, 0)
      var obar = 0.0
      for t in 0..<nt: obar += of2[t]/float(nt)
      var raw = newSeq[float](nt)
      for dt in 0..<nt:
        var acc = 0.0
        for t1 in 0..<nt: acc += of2[(t1 + dt) mod nt]*of2[t1]
        raw[dt] = acc/float(nt)
      let cf = foldC(raw)
      f2S.add s
      f2Dt.add -1.0
      f2C.add obar
      for dt in 0..nt2:
        f2S.add s
        f2Dt.add float(dt)
        f2C.add cf[dt])
  let flowKeys = measMeta("gluon", traj,
    ("flow", "generated by newBeta(g2=1): coupling-independent flow time"),
    ("Es", "spatial action density S_s/(4 pi T), ensemble Beta"))
  writeTsv(opath("flow", traj), flowKeys, ["s", "Es", "Et"], [fS, fEs, fEt])
  writeTsv(opath("loops", traj),
           measMeta("gluon", traj, ("fold", "C(dt)+C(nt-dt) over 2"),
                    ("mavg", "averaged over m at each l")),
           ["s", "l", "i", "j", "dt", "c"], [gS, gL, gI, gJ, gDt, gC])
  writeTsv(opath("f2", traj),
           measMeta("gluon", traj, ("note", "dt = -1 rows carry the slice mean of O_F2 (RAW)")),
           ["s", "dt", "c"], [f2S, f2Dt, f2C])
  echo &"  gluon traj {traj}: {stimes.len} flow times, {nsh} shapes, l = 1, 2 + F^2"

proc measWspec(u: Gauge, traj: int) =
  let nd = 2*lat.nsite
  if nd > wspecMaxDim:
    echo &"  wspec traj {traj}: SKIPPED -- dense dimension {nd} > wspecMaxDim" &
         &" {wspecMaxDim} (zgeev memory/time); raise -wspecMaxDim to force"
    return
  var a = denseDw(lat, u, M)         # X = D_W - M
  var ev = newSeq[Complex64](nd)
  zgeigs(cast[ptr float64](addr a[0]), cast[ptr float64](addr ev[0]), nd)
  var
    minAbs = abs(ev[0])
    kmin = 0
  for k in 1..<nd:
    let r = abs(ev[k])
    if r < minAbs:
      minAbs = r
      kmin = k
  var re, im, ax: seq[float]
  for k in 0..<nd:
    let r = abs(ev[k])
    if r < wspecRad or k == kmin:
      re.add ev[k].re + M          # eigenvalue of D_W itself
      im.add ev[k].im
      ax.add r
  writeTsv(opath("wspec", traj),
           measMeta("wspec", traj, ("min_abs", &"{minAbs:.17g}"), ("dim", $nd),
                    ("operator", "raw D_lat (doc/04 section 10); columns are eig(D_W)")),
           ["reDw", "imDw", "absX"], [re, im, ax])
  echo &"  wspec traj {traj}: min|D_W - {M:g}| = {minAbs:.4f}" &
       &"  ({re.len} eigenvalues within {wspecRad:g})"

