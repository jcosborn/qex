type CfgFile = tuple[traj: int, path: string]

proc discoverConfigs(): seq[CfgFile] =
  let prefix = cfgName & ".t"
  for path in walkFiles(dir/(prefix & "*")):
    let fn = extractFilename(path)
    var t: int
    try:
      t = parseInt(fn[prefix.len..^1])
    except ValueError:
      continue
    if t < tmin: continue
    if tmax > 0 and t > tmax: continue
    result.add (t, path)
  result.sort(proc(a, b: CfgFile): int = cmp(a.traj, b.traj))
  if tstride > 1:
    var s: seq[CfgFile]
    var i = 0
    while i < result.len:
      s.add result[i]
      i += tstride
    result = s

proc measureOne(u: Gauge, traj: int) =
  # The frozen rationals are only accurate inside [ratLo, ratHi]; the ensemble
  # was generated under rhmc's hard-stop monitor, but check anyway (and pure /
  # quenched configurations were never monitored at all).
  var fermionic = false
  for name in obsList:
    if name in ["cond", "currents", "scalars"]: fermionic = true
  if fermionic:
    let win = kernelWindow(actOp, u)
    if not win.inside:
      let msg = &"traj {traj}: kernel window [{win.lo:.4f}, {win.hi:.4f}]" &
                &" outside the frozen [{ratLo}, {ratHi}]: overlap measurements" &
                " on this configuration are outside the rational's validity"
      require allowWindow, msg & " (pass -allowWindow:true to measure anyway)"
      echo "  WARNING " & msg
  for name in obsList:
    if skipDone and outputDone(name, traj):
      echo &"  skip {name} traj {traj} (complete)"
      continue
    clearStats actOp
    let t0 = epochTime()
    case name
    of "cond": measCond(u, traj)
    of "currents": measCurrents(u, traj)
    of "scalars": measScalars(u, traj)
    of "gluon": measGluon(u, traj)
    of "wspec": measWspec(u, traj)
    else: discard
    echo &"  time {name} traj {traj}: {epochTime() - t0:.2f} s"
    checkSolves name

