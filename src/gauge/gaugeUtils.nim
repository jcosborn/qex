proc checkU*[F:Field](x: openArray[F]): tuple[avg,max:float] {.noinit.} =
  var a,b:float
  for mu in x.low..x.high:
    for s in x[mu]:
      let d = x[mu][s].checkU
      a += d.simdSum
      let m = d.simdMax
      if b < m: b = m
  threadRankSum a
  threadRankMax b
  const nc = x[0][0].nrows
  let vol = x[0].l.physVol
  let c = float(2*(nc*nc+1))
  a = sqrt( a / (c*float(x.len*vol)) )
  b = sqrt( b / c )
  return (a, b)

proc reunitGauge*[F:Field](g: seq[F]) =
  ## Project each link onto its group: U(1) for Nc = 1, SU(N) otherwise.
  const nc = g[0][0].nrows
  threads:
    when nc == 1:
      g.projectU
    else:
      g.projectSU
    threadBarrier()

proc checkUnitary*[F:Field](g: seq[F]): tuple[avg, max: float] =
  ## Mean/max link distance from U(1) or SU(N); does not modify g.
  const nc = g[0][0].nrows
  var a, m: float
  threads:
    let d = when nc == 1: g.checkU else: g.checkSU
    threadMaster:
      a = d.avg
      m = d.max
  (avg: a, max: m)

