template singleshift(res, f, sh, sf, sb: untyped) =
  ## res: f shifted by sh, in one of the shift buffers.
  res = f
  for mu,n in sh.pairs:
    if n>0:
      res = sb[mu] ^* res
    elif n<0:
      res = sf[mu] ^* res

template multishifts(res, f, sh, sf, sb: untyped) =
  ## res: f shifted by sh, in one of the shift buffers; f is overwritten.
  res = f
  for mu,n in sh.pairs:
    if n>0:
      res = sb[mu] ^* res
      for i in 1..<n:
        f := res
        res = sb[mu] ^* f
    elif n<0:
      res = sf[mu] ^* res
      for i in 1..<(-n):
        f := res
        res = sf[mu] ^* f

proc lrmul(res:auto, l:auto, r:auto, la,ra:bool) =
  tic("lrmul")
  if la and ra:
    res := l.adj * r.adj
    toc("la ra")
  elif la:
    res := l.adj * r
    toc("la")
  elif ra:
    res := l * r.adj
    toc("ra")
  else:
    res := l * r
    toc("direct")

proc gaugeProd*(g:auto, ptree:OrdPathTree, origin=true):auto =
  ## Evaluate plan(ptree, origin) over the links g.
  ## Outputs alias the step products unless adjoint or shifted. Other step
  ## products and the shift fields are freed before returning.
  tic("gaugeProd")
  type
    F = typeof(g[0])
    S = typeof(g[0][0])
  let
    nd = g[0].l.nDim
    pl = ptree.plan origin
  var
    sf = newseq[Shifter[F,S]](nd)
    sb = newseq[Shifter[F,S]](nd)
    gp = initTable[seq[int],F]()
    uses = initCountTable[seq[int]]()  # pending reads per step; zero counts are dropped and read back as 0
    sfi = newseq[bool](nd)
    sbi = newseq[bool](nd)
  template mark(sh:seq[int]) =
    for mu,n in sh.pairs:
      if n>0:
        sbi[mu] = true
      elif n<0:
        sfi[mu] = true
  for s in pl.steps:
    mark s.sh
    uses.inc s.l
    uses.inc s.r
  var kept = initHashSet[seq[int]]()  # step products returned without a copy
  for o in pl.outs:
    mark o.sh
    uses.inc o.key
  defer:
    for i in 0..<nd:
      if sf[i].field != nil: sf[i].field.release
      if sb[i].field != nil: sb[i].field.release
  for i in 0..<nd:
    if sfi[i]:
      sf[i] = newShifter(g[0], i, 1)
    if sbi[i]:
      sb[i] = newShifter(g[0], i, -1)
  toc("init shifts")

  proc node(k:seq[int]):F =
    if k.len==1: g[k[0]-1] else: gp[k]

  proc consumed(k: seq[int]) =
    if k.len > 1:
      uses.inc(k, -1)
      if uses[k] == 0:
        if k notin kept: gp[k].release
        gp.del k

  for s in pl.steps:
    let
      l = node s.l
      r = node s.r
      la = s.la
      ra = s.ra
      sh = s.sh
    var needs = 0
    for x in sh:
      needs = max(needs, abs x)
    var res = newOneOf(r)
    threads:
      var rr {.cursor.} = r
      if needs==1:
        singleshift(rr, r, sh, sf, sb)
      elif needs>1:
        res := r
        multishifts(rr, res, sh, sf, sb)
      res.lrmul(l,rr,la,ra)
    gp[s.key] = res
    consumed(s.l)
    consumed(s.r)
  toc("gaugeProd prod")
  var res = newseq[F](pl.outs.len)
  for i,o in pl.outs.pairs:
    let t = node o.key
    let sh = o.sh
    var needs = 0
    for x in sh: needs = max(needs, abs x)
    if not o.adj and needs == 0:
      res[i] = t
      kept.incl o.key
    else:
      res[i] = newOneOf t
      if o.adj:
        threads: res[i] := t.adj
      if needs > 0:
        threads:
          var r {.cursor.} = t
          if o.adj: r = res[i]
          var shifted {.cursor.}: F
          if needs == 1:
            singleshift(shifted, r, sh, sf, sb)
          else:
            res[i] := r
            multishifts(shifted, res[i], sh, sf, sb)
          res[i] := shifted
    consumed(o.key)
  result = res
  toc("done")

proc wilsonLines*(g:auto, lines:openarray[seq[int]]):auto =
  ## Compute the trace of ordered product of gauge links, the Wilson Line.
  ## Each line is given as a list of integers +/- 1..nd, where the sign
  ## denotes forward/backward and the number denotes the dimension.
  ## Note that the simplification has a runtime complexity of O(N^3) for N=lines.len.
  tic()
  let n = lines.len
  let rs = g.gaugeProd(lines.optimalPairs, false)
  toc("wilsonLines prod")
  type R = typeof(trace(g[0]))
  var
    r: R
    ts = newseq[R](n)
  const nc = g[0][0].ncols
  let
    vol = g[0].l.physVol
    fac = 1.0/float(vol*nc)
  for i,s in rs.pairs:
    threads:
      r = s.trace
    ts[i] := r*fac
  for i,s in rs.pairs:
    if s notin g and s notin rs.toOpenArray(0,i-1): s.release
  toc("wilsonLines trace")
  return ts

proc wline*(g:auto, line:openarray[int]):auto =
  return g.wilsonLines([@line])[0]

proc allCorners(path:openarray[int]):seq[seq[int]] =
  let np = path.len
  result = newseq[seq[int]]()
  var old = 0
  for i,x in path.pairs:
    if x!=old:
      var p = newseq[int](np)
      for j in 0..<np:
        p[j] = path[(j+i) mod np]
      result.add p
      old = x
  # echo "allCorners: ",result

proc fmunuCoeffs_fun(loop:int):auto =
  var k:array[5,float]
  case loop
  of 1:
    return [1.0,0,0,0,0]
  of 3:
    k[4] = 1.0/90.0
  of 4:
    k[4] = 0.0
  of 5:
    k[4] = 1.0/180.0
  else:
    discard
  k[0] = 19.0/9.0 - 55.0*k[4]
  k[1] = 1.0/36.0 - 16.0*k[4]
  k[2] = 64.0*k[4] - 32.0/45.0
  k[3] = 1.0/15.0 - 6.0*k[4]
  return k

proc fmunuCoeffs(loop:int):auto =
  const FmunuCoeffs =
    [ fmunuCoeffs_fun(1)
    , fmunuCoeffs_fun(3)
    , fmunuCoeffs_fun(4)
    , fmunuCoeffs_fun(5)
    ]
  case loop
  of 1:
    result = FmunuCoeffs[0]
  of 3:
    result = FmunuCoeffs[1]
  of 4:
    result = FmunuCoeffs[2]
  of 5:
    {.linearScanEnd.}
    result = FmunuCoeffs[3]
  else:
    qexError("fmunuCoeffs uses loop in [1,3,4,5], but got ",loop)

proc fmunuPTree_fun(mu,nu,loop:int):auto =
  tic()
  var lp = newseq[seq[int]]()
  block:
    let
      mu = mu+1
      nu = nu+1
    lp.add allCorners @[-mu,-nu,mu,nu]  # 1x1
    if loop>=3:
      lp.add allCorners @[-mu,-mu,-nu,-nu,mu,mu,nu,nu]  # 2x2
    if loop>=4:
      lp.add allCorners @[-mu,-mu,-nu,mu,mu,nu]  # 2x1
      lp.add allCorners @[-mu,-nu,-nu,mu,nu,nu]  # 1x2
      lp.add allCorners @[-mu,-mu,-mu,-nu,mu,mu,mu,nu]  # 3x1
      lp.add allCorners @[-mu,-nu,-nu,-nu,mu,nu,nu,nu]  # 1x3
    if loop==3 or loop==5:
      lp.add allCorners @[-mu,-mu,-mu,-nu,-nu,-nu,mu,mu,mu,nu,nu,nu]  # 3x3
  result = lp.optimalPairs
  toc("compute PTree")

proc fmunuPTree(mu,nu,loop:int):auto =
  const lps = [-1,0,-1,1,2,3]
  let lp = lps[loop]
  memoize(lp,mu,nu):
    fmunuPTree_fun(mu,nu,loop)

proc fmunu*(g:auto, mu,nu:int, loop=1):auto =
  ## mu,nu: 0..<nd
  ## loop: 1,3,4,5
  ## returns the traceless antihermitian F_munu from the clover
  tic("fmunu")
  if loop notin [1,3,4,5]:
    qexError("fmunu uses loop in [1,3,4,5], but got ",loop)
  const lpc = [4,4,8,8,4]  # counts of distinct loops in order of 1x1, 2x2, 1x2, 1x3, 3x3
  let cs = fmunuCoeffs loop
  let ptree = fmunuPTree(mu,nu,loop)
  toc("fmunuPTree")
  let fs = g.gaugeProd ptree
  toc("gaugeProd")
  let f = newOneOf(fs[0])
  threads:
    f := 0
    var i0 = 0
    for jc in 0..<loop:
      var j = jc
      if loop==3 and jc==2:
        j = 4
      let n = lpc[j]
      let ni = cs[j]/n.float
      for ir in f:
        var t:type(load1(f[0]))
        for i in 0..<n:
          t += fs[i0+i][ir]
        f[ir] += ni*t
      i0 += n
    f.projectTAH
  toc("single fmunu")
  return f

proc fmunu*(g:auto, loop=1):auto =
  ## loop: 1,3,4,5
  ## returns the traceless antihermitian F[mu][nu] where mu>nu
  tic("fmunu")
  type F = type(g[0])
  let nd = g[0].l.nDim
  var f = newseq[seq[F]](nd)  # only partially initialized
  for mu in 1..<nd:
    f[mu].newseq(mu)
    for nu in 0..<mu:
      f[mu][nu] = g.fmunu(mu,nu,loop)
  toc("fmunu tensor")
  return f

proc reTrMul(x,y:auto):auto =
  var d: type(eval(toDouble(redot(x[0],y[0]))))
  for ir in x:
    d += redot(x[ir].adj, y[ir])
  result = simdSum(d)
  x.l.threadRankSum(result)

proc densityE*(f:auto):auto =
  ## construct E from F_munu
  ## returns (E_s, E_t)
  tic("densityE")
  let nd = f[1][0].l.nDim
  var es,et:float
  for mu in 1..<nd:
    for nu in 0..<mu:
      threads:
        let t = reTrMul(f[mu][nu], f[mu][nu])
        threadSingle:
          if mu<nd-1:
            es += t
          else:
            et += t
  let vi = -1.0/f[1][0].l.physVol.float
  toc("end")
  return (vi*es,vi*et)

proc topoQ*(f:auto):auto =
  ## construct Q from F_munu
  ## returns Q
  tic("topoQ")
  var q:float
  threads:
    let
      a = reTrMul(f[1][0], f[3][2])
      b = reTrMul(f[2][0], f[3][1])
      c = reTrMul(f[2][1], f[3][0])
    threadSingle:
      q = -1.0/(4.0*PI*PI)*(a-b+c)
  toc("end")
  return q

