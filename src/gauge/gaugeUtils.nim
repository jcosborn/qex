proc default*(g: Gauge) =
  let nd = g.u.len
  threads:
    if g.group in {gkU, gkSU, gkO, gkSO}:
      for i in 0..<nd:
        g.u[i] := 1
    else:
      for i in 0..<nd:
        g.u[i] := 0

