proc newGauge*(l: Layout, gk: GroupKind, n: static[int] = getDefaultNc()): auto =
  type LCM = type l.ColorMatrix(n)
  type GaugeT = Gauge[LCM]
  let nd = l.nDim
  result = new GaugeT
  result.n = n
  result.group = gk
  result.u.newSeq(nd)
  for i in 0..<nd:
    result.u[i].new(l)
  result.default

