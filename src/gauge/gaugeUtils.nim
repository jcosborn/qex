proc plaq2*[T](gg:openArray[T]):auto =
  mixin adj
  tic("plaq2")
  let g = cast[ptr cArray[T]](unsafeAddr(gg[0]))
  let lo = g[0].l
  let nd = lo.nDim
  let nc = g[0][0].ncols
  #let np = (nd*(nd-1)) div 2
  var m = lo.ColorMatrix()
  var s0 = lo.ColorMatrix()
  #var t0 = lo.ColorMatrix()
  var s1 = lo.ColorMatrix()
  #var t1 = lo.ColorMatrix()
  var tr:type(trace(m))
  toc("setup")
  threads:
    tic("plaq2 threads")
    m := 0
    toc("zero")
    for mu in 1..<nd:
      for nu in 0..<mu:
        tic("plaq2 loop")
        #toc("before shift1")
        shift(s0, mu,1, g[nu])
        toc("shift1")
        shift(s1, nu,1, g[mu])
        toc("shift2")
        #echo "s0: ", trace(s0)
        #echo "s1: ", trace(s1)
        m += (g[mu]*s0) * (g[nu]*s1).adj
        #m += (g[mu]*s0) * (g[nu]*s1)
        #echo mu, " ", nu, " ", trace(m)/nc
        toc("mul", flops=lo.nSites.float*float(3*fcmmul(nc)+fcmadd(nc)))
    toc("work")
    tr = trace(m)
    toc("trace")
  toc("end")
  result = tr/(lo.physVol.float*0.5*float(nd*(nd-1)*nc))

proc plaq3*[T](g: seq[T]): auto =
  mixin adj, newTransporters
  tic("plaq3")
  let lo = g[0].l
  let nd = lo.nDim
  let nc = g[0][0].ncols
  let t = newTransporters(g, g[0], 1)
  var m = lo.ColorMatrix()
  var tr: type(trace(m))
  toc("setup")
  threads:
    tic("plaq3 threads")
    m := 0
    toc("zero")
    for mu in 1..<nd:
      for nu in 0..<mu:
        tic("plaq3 loop")
        #m += (t[mu]^*g[nu]) * (t[nu]^*g[mu]).adj
        discard t[mu]^*!g[nu]
        toc("transport1", flops=lo.nSites.float*float(fcmmul(nc)))
        discard t[nu]^*!g[mu]
        threadBarrier()
        toc("transport2", flops=lo.nSites.float*float(fcmmul(nc)))
        m += t[mu].field * t[nu].field.adj
        #echo mu, " ", nu, " ", trace(m)/nc
        toc("mul", flops=lo.nSites.float*float(fcmmul(nc)+fcmadd(nc)))
    toc("work")
    tr = trace(m)
    toc("trace")
  toc("end")
  result = tr/(lo.physVol.float*0.5*float(nd*(nd-1)*nc))

