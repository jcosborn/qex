      r.skip(0x0f1e2d3c4b5a6978u64, 195)
      for i in 0..<part:
        discard r.next
      for x in res[part]:
        let u = r.uniform
        check(cast[uint64](u) == x)
        check(u > 0.0 and u <= 1.0)

      var a,b: Philox4x64
      a.seedIndep(1337, 0)
      b.seedIndep(1337, 0)
      for i in 0..<part:
        discard a.next
